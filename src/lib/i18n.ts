export const dictionaries: Record<Lang, Record<Key, string>> = { en, ur };

/** A message kept as data, so it can be shown in whichever language is active. */
export type Msg = { key: Key; vars?: Record<string, Var> };
/** A plain string is shown as typed; `term` is a known sample word; `msg` is a nested message. */
export type Var = string | number | { term: string } | { msg: Msg };

/** Keeps names, numbers and dates readable inside right-to-left sentences. */
const isolate = (value: string) => (value ? `⁨${value}⁩` : value);

export function term(value: string, lang: Lang = "en"): string {
  const key = `term.${value}`;
  return key in en ? dictionaries[lang][key as Key] : value;
}

export function t(key: Key, vars: Record<string, Var> = {}, lang: Lang = "en"): string {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (all, name: string) => {
    const v = vars[name];
    if (v === undefined) return all;
    if (typeof v === "object") return "term" in v ? term(v.term, lang) : render(v.msg, lang);
    return lang === "ur" ? isolate(String(v)) : String(v);
  });
}

export const render = (message: Msg, lang: Lang = "en"): string =>
  t(message.key, message.vars, lang);

export const LANG_STORAGE_KEY = "stitchsure.lang";

function bind(lang: Lang, setLang: (next: Lang) => void) {
  return {
    lang,
    setLang,
    t: (key: Key, vars?: Record<string, Var>) => t(key, vars, lang),
    term: (value: string) => term(value, lang),
    msg: (message: Msg) => render(message, lang),
  };
}

const LangContext = createContext(bind("en", () => {}));

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setState] = useState<Lang>("en");
  // Read the saved choice after mounting, so server and first client render match.
  useEffect(() => {
    try {
      if (window.localStorage.getItem(LANG_STORAGE_KEY) === "ur") setState("ur");
    } catch {
      // Storage can be blocked; English is used.
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = useCallback((next: Lang) => {
    setState(next);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch {
      // The choice still applies for this visit.
    }
  }, []);
  const value = useMemo(() => bind(lang, setLang), [lang, setLang]);
  return createElement(LangContext.Provider, { value }, children);
}

export const useLang = () => useContext(LangContext);
