export type Key = keyof typeof en;
export type Vars = Record<string, string | number>;

const fill = (text: string, vars: Vars = {}) =>
  text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));

export function t(key: Key, vars?: Vars): string {
  return fill(en[key], vars);
}

/** Translates a known sample-data value. Anything a person typed is returned unchanged. */
export function term(value: string): string {
  const key = `term.${value}`;
  return key in en ? t(key as Key) : value;
}
